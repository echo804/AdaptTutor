def add_runs(para, text):
    parts = re.split(r"\*\*(.+?)\*\*", text)
    for i, part in enumerate(parts):
        if not part:
            continue
        run = para.add_run(part)
        if i % 2 == 1:
            run.bold = True
            run.font.color.rgb = INK
        else:
            run.font.color.rgb = GRAY

def add_label(para, label, text, color):
    r1 = para.add_run(label)
    r1.bold = True
    r1.font.color.rgb = color
    parts = re.split(r"\*\*(.+?)\*\*", text)
    for i, part in enumerate(parts):
        if not part:
            continue
        run = para.add_run(part)
        if i % 2 == 1:
            run.bold = True
            run.font.color.rgb = color
        else:
            run.font.color.rgb = GRAY

def build():
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "微软雅黑"
    style.font.size = Pt(10.5)
    style._element.rPr.rFonts.set(
        "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", "微软雅黑"
    )

    title = doc.add_heading("AdaptTutor 项目面试问答（大模型应用 / Agent 开发岗）", level=0)
    for run in title.runs:
        run.font.color.rgb = INK
        run.font.name = "微软雅黑"
    sub = doc.add_paragraph()
    r = sub.add_run("每个问题含四个部分：考察点（面试官想看什么）→ 我的回答（项目真实做法）→ 诚实边界（现状缺陷）→ 改进方案（如何补）。加粗为面试重点。")
    r.font.size = Pt(9.5)
    r.font.color.rgb = AMBER

    for chapter, items in QA:
        h = doc.add_heading(chapter, level=1)
        for run in h.runs:
            run.font.color.rgb = INK
        for item in items:
            if len(item) == 5:
                q, probe, answer, boundary, improve = item
            else:
                q, probe, body = item
                probe = re.sub(r"^考察点：", "", probe)
                body = re.sub(r"^我的回答（诚实）：", "", body)
                body = re.sub(r"^我的回答：", "", body)
                parts = re.split(r"(诚实边界：|改进方案：)", body)
                answer = parts[0].strip()
                boundary = ""
                improve = ""
                # parts = [回答, 标签1, 内容1, 标签2, 内容2, ...]
                for i in range(1, len(parts), 2):
                    label = parts[i]
                    content = parts[i + 1].strip() if i + 1 < len(parts) else ""
                    if label.startswith("诚实边界"):
                        boundary += content
                    elif label.startswith("改进方案"):
                        improve += content
            qh = doc.add_heading(q, level=2)
            for run in qh.runs:
                run.font.color.rgb = RGBColor(0x1F, 0x2A, 0x36)

            p1 = doc.add_paragraph()
            p1.paragraph_format.line_spacing = 1.3
            p1.paragraph_format.space_after = Pt(4)
            add_label(p1, "考察点：", probe, AMBER)

            p2 = doc.add_paragraph()
            p2.paragraph_format.line_spacing = 1.3
            p2.paragraph_format.space_after = Pt(4)
            add_label(p2, "我的回答：", "", INK)
            add_runs(p2, answer)

            p3 = doc.add_paragraph()
            p3.paragraph_format.line_spacing = 1.3
            p3.paragraph_format.space_after = Pt(4)
            add_label(p3, "诚实边界：", boundary or "（无独立补充项，要点已包含在回答中）", RGBColor(0x9C, 0x42, 0x2B))

            p4 = doc.add_paragraph()
            p4.paragraph_format.line_spacing = 1.3
            p4.paragraph_format.space_after = Pt(12)
            add_label(p4, "改进方案：", improve or "（无独立补充项，见回答或对应追问）", RGBColor(0x1F, 0x7A, 0x44))

    # 第十章 八股文：模块 H2 + 题 H3 + 要点/结合点两段
    bh = doc.add_heading("第十章 大模型 / Agent 高频八股（答案要点 + 与项目结合点）", level=1)
    for run in bh.runs:
        run.font.color.rgb = INK
    intro = doc.add_paragraph()
    r = intro.add_run("背法：先记「一句话要点」，再用「与项目结合点」把它接到项目上（⭐=面试时能自然引出的）。")
    r.font.size = Pt(9.5)
    r.font.color.rgb = GRAY
    for module, items in BAGU:
        mh = doc.add_heading(module, level=2)
        for run in mh.runs:
            run.font.color.rgb = RGBColor(0x1F, 0x2A, 0x36)
        for q, point, link in items:
            qh = doc.add_heading(q, level=3)
            for run in qh.runs:
                run.font.size = Pt(11)
                run.font.color.rgb = RGBColor(0x1F, 0x2A, 0x36)
            p = doc.add_paragraph()
            p.paragraph_format.line_spacing = 1.3
            p.paragraph_format.space_after = Pt(3)
            add_label(p, "要点：", "", INK)
            add_runs(p, point)
            p2 = doc.add_paragraph()
            p2.paragraph_format.line_spacing = 1.3
            p2.paragraph_format.space_after = Pt(10)
            add_label(p2, "结合点：", "", RGBColor(0x1F, 0x7A, 0x44))
            add_runs(p2, link)

    candidates = [r"E:\pc\AdaptTutor项目面试问答-大模型Agent岗.docx", os.path.join(os.path.expanduser("~"), "Desktop", "AdaptTutor项目面试问答-大模型Agent岗.docx")]
    out = next((c for c in candidates if os.path.isdir(os.path.dirname(c))), candidates[-1])
    doc.save(out)
    print(f"已生成: {out}")

if __name__ == "__main__":
    build()
