def add_runs(para, text, bold_color=None):
    """解析 **加粗** 标记，普通文本黑色，加粗文本用主题色。"""
    parts = re.split(r"\*\*(.+?)\*\*", text)
    for i, part in enumerate(parts):
        if not part:
            continue
        run = para.add_run(part)
        if i % 2 == 1:  # 加粗段
            run.bold = True
            run.font.color.rgb = bold_color or INK
        else:
            run.font.color.rgb = GRAY

def build():
    doc = Document()

    # 全局默认字体（中文）
    style = doc.styles["Normal"]
    style.font.name = "微软雅黑"
    style.font.size = Pt(11)
    style._element.rPr.rFonts.set(
        "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", "微软雅黑"
    )

    # 封面标题
    title = doc.add_heading("AdaptTutor 项目面试复习问答", level=0)
    for run in title.runs:
        run.font.color.rgb = INK
        run.font.name = "微软雅黑"
    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r = sub.add_run("通用自适应学习引擎 · 学习闭环：诊断 → 路径 → 引导 → 溯源 → 遗忘复习")
    r.font.size = Pt(10.5)
    r.font.color.rgb = AMBER
    sub2 = doc.add_paragraph()
    r2 = sub2.add_run("（回答中加粗着色为面试重点；全篇尽量使用中文表述，技术名词保留原名）")
    r2.font.size = Pt(9)
    r2.font.color.rgb = GRAY

    for chapter, items in QA:
        h = doc.add_heading(chapter, level=1)
        for run in h.runs:
            run.font.color.rgb = INK
        for q, a in items:
            qh = doc.add_heading(q, level=2)
            for run in qh.runs:
                run.font.color.rgb = RGBColor(0x1F, 0x2A, 0x36)
            p = doc.add_paragraph()
            p.paragraph_format.space_after = Pt(10)
            p.paragraph_format.line_spacing = 1.35
            add_runs(p, a)

    out = os.path.join(os.path.expanduser("~"), "Desktop", "AdaptTutor项目面试复习问答.docx")
    doc.save(out)
    print(f"已生成: {out}")

if __name__ == "__main__":
    build()
