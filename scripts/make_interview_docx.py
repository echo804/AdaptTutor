def add_runs(para, text):
    parts = re.split(r"\*\*(.+?)\*\*", text)
    for i, part in enumerate(parts):
        if not part:
            continue
        run = para.add_run(part)
        if i % 2 == 1:
            run.bold = True
            run.font.color.rgb = INK
        else:
            run.font.color.rgb = GRAY

def add_label(para, label, text, color):
    r1 = para.add_run(label)
    r1.bold = True
    r1.font.color.rgb = color
    parts = re.split(r"\*\*(.+?)\*\*", text)
    for i, part in enumerate(parts):
        if not part:
            continue
        run = para.add_run(part)
        if i % 2 == 1:
            run.bold = True
            run.font.color.rgb = color
        else:
            run.font.color.rgb = GRAY

def build():
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "微软雅黑"
    style.font.size = Pt(10.5)
    style._element.rPr.rFonts.set(
        "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", "微软雅黑"
    )

    title = doc.add_heading("AdaptTutor 项目面试问答（大模型应用 / Agent 开发岗）", level=0)
    for run in title.runs:
        run.font.color.rgb = INK
        run.font.name = "微软雅黑"
    sub = doc.add_paragraph()
    r = sub.add_run("每个问题含四个部分：考察点（面试官想看什么）→ 我的回答（项目真实做法）→ 诚实边界（现状缺陷）→ 改进方案（如何补）。加粗为面试重点。")
    r.font.size = Pt(9.5)
    r.font.color.rgb = AMBER

    for chapter, items in QA:
        h = doc.add_heading(chapter, level=1)
        for run in h.runs:
            run.font.color.rgb = INK
        for item in items:
            if len(item) == 5:
                q, probe, answer, boundary, improve = item
            else:
                q, probe, body = item
                probe = re.sub(r"^考察点：", "", probe)
                body = re.sub(r"^我的回答（诚实）：", "", body)
                body = re.sub(r"^我的回答：", "", body)
                parts = re.split(r"(诚实边界：|改进方案：)", body)
                answer = parts[0].strip()
                boundary = parts[2].strip() if len(parts) > 2 else ""
                improve = parts[4].strip() if len(parts) > 4 else ""
            qh = doc.add_heading(q, level=2)
            for run in qh.runs:
                run.font.color.rgb = RGBColor(0x1F, 0x2A, 0x36)

            p1 = doc.add_paragraph()
            p1.paragraph_format.line_spacing = 1.3
            p1.paragraph_format.space_after = Pt(4)
            add_label(p1, "考察点：", probe, AMBER)

            p2 = doc.add_paragraph()
            p2.paragraph_format.line_spacing = 1.3
            p2.paragraph_format.space_after = Pt(4)
            add_label(p2, "我的回答：", "", INK)
            add_runs(p2, answer)

            p3 = doc.add_paragraph()
            p3.paragraph_format.line_spacing = 1.3
            p3.paragraph_format.space_after = Pt(4)
            add_label(p3, "诚实边界：", "", RGBColor(0x9C, 0x42, 0x2B))
            add_runs(p3, boundary)

            p4 = doc.add_paragraph()
            p4.paragraph_format.line_spacing = 1.3
            p4.paragraph_format.space_after = Pt(12)
            add_label(p4, "改进方案：", "", RGBColor(0x1F, 0x7A, 0x44))
            add_runs(p4, improve)

    out = os.path.join(os.path.expanduser("~"), "Desktop", "AdaptTutor项目面试问答-大模型Agent岗.docx")
    doc.save(out)
    print(f"已生成: {out}")

if __name__ == "__main__":
    build()
